export function AdminSidebar() {
  const pathname = usePathname();
  const { can } = usePermissions();

  // Permission-driven navigation: hide items the current admin cannot access.
  // Items without a permission value are visible to every admin.
  const visibleItems = navItems.filter(
    (item) => !item.permission || can(item.permission),
  );

  return (
    <aside className="flex h-full flex-col border-r border-gray-200 bg-white dark:border-gray-800 dark:bg-gray-950">
      {/* Logo */}
      <div className="flex h-14 items-center gap-2 border-b border-gray-100 px-5 dark:border-gray-800">
        <div className="flex h-7 w-7 items-center justify-center rounded-lg bg-amber-600 text-[10px] font-bold text-white">
          A
        </div>
        <span className="text-sm font-semibold text-gray-900 dark:text-gray-100">
          Admin Panel
        </span>
      </div>

      {/* Navigation */}
      <nav className="flex-1 space-y-0.5 overflow-y-auto p-3">
        {visibleItems.map((item) => {
          const isActive =
            pathname === item.href || pathname.startsWith(item.href + '/');

          return (
            <Link
              key={item.href}
              href={item.href}
              className={cn(
                'flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium transition-colors',
                isActive
                  ? 'bg-amber-50 text-amber-700 dark:bg-amber-900/20 dark:text-amber-400'
                  : 'text-gray-600 hover:bg-gray-50 hover:text-gray-900 dark:text-gray-400 dark:hover:bg-gray-800 dark:hover:text-gray-200',
              )}
            >
              {item.icon}
              <span>{item.label}</span>
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}
